// Extract only reviewed, DOM-free business logic for JavaScriptCore. The PWA is never edited.
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm'), crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const sha = value => crypto.createHash('sha256').update(value).digest('hex');
function buildNativeDomain() {
  const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
  const matches = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
  if (matches.length !== 1) throw Error('Expected one PWA application script');
  const source = matches[0][1], inventory = [];
  function section(start, end) {
    const a = source.indexOf(start), b = source.indexOf(end, a + start.length);
    if (a < 0 || b < 0 || source.indexOf(start, a + start.length) !== -1) throw Error('Ambiguous domain boundary: ' + start);
    const code = source.slice(a, b);
    inventory.push({start, end, sha256: sha(code)});
    return code;
  }
  const pieces = [
    section('const todayKey =', '/* 按当前时间猜默认餐次 */'),
    section('let store = {};', 'function readLocal('),
    section('function normalizeCompletion(', 'function saveBurn('),
    section('function normalizeWeight(', '/* TEST-EXTRACT-HEALTH-MODEL-A */'),
    section('function healthNumber(', 'function weightChartGeometry('),
    section('function dataSnapshot(', 'let initialData;'),
    section('const sum = arr =>', '/* ---------------- 提示词'),
    section('const LABELS =', '/* ================= 圆环模型'),
    section('/* TEST-EXTRACT-BURN-A */', '/* TEST-EXTRACT-BURN-B */'),
    section('const MEAL_ALIASES =', '/* ================= iOS 风格选择弹窗'),
    section('function validateBackup(', 'async function applyImport(')
  ];
  const adapter = fs.readFileSync(path.join(root, 'native-ios/domain/adapter.js'), 'utf8');
  const code = "// Generated by _tools/build-native-domain.js. Do not edit.\n'use strict';\n" +
    '(function(scope){\nconst N = v => Number.isFinite(v) ? Math.round(v * 10) / 10 : 0;\n' +
    pieces.join('\n') + '\n' + adapter + '\n})(globalThis);\n';
  // A newly introduced browser dependency fails the build, rather than being silently stubbed.
  if (/\b(?:document|window|navigator|localStorage|fetch|XMLHttpRequest|WebSocket|WKWebView)\b|\$\s*\(/.test(code))
    throw Error('A browser or network API leaked into the native domain');
  new vm.Script(code, {filename:'domain.js'});
  const directory = path.join(root, 'native-ios/domain');
  for (const name of ['domain.js', 'manifest.json']) {
    const target = path.join(directory, name);
    if (fs.existsSync(target) && fs.lstatSync(target).isSymbolicLink()) throw Error('Refusing linked output: ' + name);
  }
  fs.writeFileSync(path.join(directory, 'domain.js'), code);
  const manifest = {schema:1, source:'index.html', sourceSHA256:sha(html), adapterSHA256:sha(adapter), domainSHA256:sha(code), sections:inventory};
  fs.writeFileSync(path.join(directory, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  if (sha(fs.readFileSync(path.join(root, 'index.html'), 'utf8')) !== manifest.sourceSHA256) throw Error('PWA changed during extraction');
  return {code, manifest};
}
module.exports = {buildNativeDomain};
if (require.main === module) { const result=buildNativeDomain(); console.log('Native domain generated: ' + result.manifest.sections.length + ' reviewed pure sections; SHA256 ' + result.manifest.domainSHA256); }
