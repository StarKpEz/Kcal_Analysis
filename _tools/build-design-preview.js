// Generate a review copy; never writes index.html, sw.js, or production data.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const scriptMatches = [...source.matchAll(/<script>([\s\S]*?)<\/script>/g)];
if (scriptMatches.length !== 1) throw new Error('Expected one app script; review the preview builder after structural changes.');
const originalScript = scriptMatches[0][1];
const boundary = originalScript.indexOf('/* ---------------- 版本与更新');
if (boundary < 0) throw new Error('Missing update boundary; refusing to copy service worker code.');
let script = originalScript.slice(0, boundary).replace(/\blocalStorage\b/g, 'previewStorage');
script = script.replace("isHealth ? '健康' : '🍽️ 饮食'", "isHealth ? '健康' : (document.documentElement.classList.contains('design-preview-new') ? '饮食' : '🍽️ 饮食')");
script += `
// Preview-only controls. No service worker, durable storage, or external requests.
$('verLabel').textContent = '设计草案 A · 演示数据';
$('btnUpdate').textContent = '重置演示';
$('btnUpdate').addEventListener('click', () => location.reload());
$('btnReloadData').addEventListener('click', () => location.reload());
window.addEventListener('message', event => {
  if (event.source !== parent || event.data?.type !== 'kcal-design-preview') return;
  const message = event.data;
  if (message.action === 'style' && typeof message.enabled === 'boolean') {
    document.getElementById('designTheme').disabled = !message.enabled;
    document.documentElement.classList.toggle('design-preview-new', message.enabled);
    $('pageTitle').textContent = appRoute === 'diet' ? (message.enabled ? '饮食' : '🍽️ 饮食') : '健康';
  }
  if (message.action === 'route') {
    const allowed = ['diet','health','energy','weight','training','sleep','import'];
    if (message.route === 'settings') { closeSet(); openSet(); }
    else if (allowed.includes(message.route)) { closeSet(); navigateApp(message.route); }
  }
});
parent.postMessage({type:'kcal-design-preview-ready'}, '*');
`;
new vm.Script(script, { filename: 'preview/app.html' });
if (/localStorage|sessionStorage|navigator\.serviceWorker/.test(script)) throw new Error('Persistent storage or service worker leaked into preview.');
let html = source.replace(scriptMatches[0][0], () => '<script src="demo.js"></script>\n<script>' + script + '</script>');
const navigationSource = fs.readFileSync(path.join(root,'preview/navigation.js'),'utf8');
new vm.Script(navigationSource,{filename:'preview/navigation.js'});
const navigationVersion = crypto.createHash('sha256').update(navigationSource).digest('hex').slice(0,12);
html = html.replace('</body>', '<script src="navigation.js?v='+navigationVersion+'"></script>\n</body>');
html = html.replace(/<link[^>]+rel="(?:manifest|icon|apple-touch-icon)"[^>]*>\r?\n/g, '');
html = html.replace(/<meta[^>]+name="apple-mobile-web-app-[^"]+"[^>]*>\r?\n/g, '');
html = html.replace('<title>热量记账 · 拍照算热量</title>', '<title>健康记录 · 设计预览</title>');
const themeVersion = crypto.createHash('sha256').update(fs.readFileSync(path.join(root,'preview/theme.css'))).digest('hex').slice(0,12);
html = html.replace('</head>', '<meta http-equiv="Content-Security-Policy" content="connect-src \'none\'; object-src \'none\'; base-uri \'none\'; form-action \'none\'">\n<link id="designTheme" rel="stylesheet" href="theme.css?v='+themeVersion+'">\n</head>');
html = html.replace('<html lang="zh-CN">', '<html lang="zh-CN" class="design-preview-new">');
html = html.replace('<span>🍽️ 摄入热量</span>', '<span><span class="preview-emoji" aria-hidden="true">🍽️ </span>摄入热量</span>');
html = html.replace(/href="\.\/docs\//g, 'href="../docs/');
html = '<!-- Generated by _tools/build-design-preview.js. Edit theme.css or the builder, not this copy. -->\n' + html;
new vm.Script([...html.matchAll(/<script>([\s\S]*?)<\/script>/g)][0][1]);
fs.mkdirSync(path.join(root, 'preview'), { recursive: true });
fs.writeFileSync(path.join(root, 'preview/app.html'), html);
// Version only preview resources; production caches and records stay untouched.
const previewVersion = crypto.createHash('sha256').update(html).digest('hex').slice(0,12);
const shellPath = path.join(root,'preview/index.html');
const shell = fs.readFileSync(shellPath,'utf8');
const updatedShell = shell.replace(/src="app\.html(?:\?v=[0-9a-f]{12})?#\/health"/, 'src="app.html?v='+previewVersion+'#/health"');
if(updatedShell === shell && !shell.includes('src="app.html?v='+previewVersion+'#/health"')) throw new Error('Preview iframe source not found');
if(updatedShell !== shell) fs.writeFileSync(shellPath,updatedShell);
console.log('Built preview/app.html; production files unchanged.');
